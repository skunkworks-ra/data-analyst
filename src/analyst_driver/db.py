"""
db.py — the run index.

The database is an **index, not the truth**. Every row here is derived from a
file under the run root, and :func:`rebuild` must be able to reconstruct the
whole database from those files alone. Nothing in the driver may read state that
exists only in the database or only in RAM.

On-disk layout, which is the authority::

    <run_root>/
        driver.db                     <- this database; disposable
        <run_key>/
            run.json                  <- run metadata, written once at init
            turns/0001.json           <- one record per turn, written at record time
            scripts/                  <- scripts generated by ms_modify
            logs/                     <- executor stdout/stderr

A turn record is written to ``turns/NNNN.json`` *before* the corresponding rows
are inserted. If the process dies between the two, ``rebuild`` recovers the turn.
If it dies before the file is written, the turn did not happen.

SQLite is chosen for having no server. Keep the run root on local disk: SQLite
file locking over NFS is unreliable. All SQL lives in this module and the DDL is
kept ANSI-portable, so moving to Postgres is a DDL rewrite and a placeholder
change rather than a redesign. The two known non-portable points are marked
``PORTABILITY``.
"""

from __future__ import annotations

import hashlib
import json
import sqlite3
from collections.abc import Iterator
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

# --------------------------------------------------------------------------
# Vocabulary
# --------------------------------------------------------------------------

#: Terminal and non-terminal states a run may be in.
RUN_STATUS = ("active", "done", "failed", "needs_human")

#: What became of a turn. ``accepted`` is the one that counted for its stage;
#: at most one accepted turn exists per (run, stage).
TURN_OUTCOME = ("pending", "accepted", "retried", "failed")

#: Executor-reported job states. Mirrors the executor protocol.
JOB_STATE = ("pending", "running", "done", "failed")

#: Artifact kinds. Free-form enough to extend without a migration.
ARTIFACT_KIND = ("caltable", "ms", "image", "script", "plot", "log", "other")


# --------------------------------------------------------------------------
# Layout
# --------------------------------------------------------------------------


def db_path(run_root: Path | str) -> Path:
    return Path(run_root) / "driver.db"


def run_dir(run_root: Path | str, run_key: str) -> Path:
    return Path(run_root) / run_key


def run_json_path(run_root: Path | str, run_key: str) -> Path:
    return run_dir(run_root, run_key) / "run.json"


def turns_dir(run_root: Path | str, run_key: str) -> Path:
    return run_dir(run_root, run_key) / "turns"


def turn_json_path(run_root: Path | str, run_key: str, ordinal: int) -> Path:
    return turns_dir(run_root, run_key) / f"{ordinal:04d}.json"


def scripts_dir(run_root: Path | str, run_key: str) -> Path:
    return run_dir(run_root, run_key) / "scripts"


def logs_dir(run_root: Path | str, run_key: str) -> Path:
    return run_dir(run_root, run_key) / "logs"


def ensure_run_dirs(run_root: Path | str, run_key: str) -> Path:
    """Create the directory tree for one run and return its root."""
    d = run_dir(run_root, run_key)
    for sub in (turns_dir, scripts_dir, logs_dir):
        sub(run_root, run_key).mkdir(parents=True, exist_ok=True)
    return d



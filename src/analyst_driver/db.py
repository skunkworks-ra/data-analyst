def get_run(conn: sqlite3.Connection, run_key: str) -> sqlite3.Row | None:
    return conn.execute("SELECT * FROM runs WHERE run_key = ?", (run_key,)).fetchone()


def active_runs(conn: sqlite3.Connection) -> list[sqlite3.Row]:
    """Runs the driver should still consider. Feeds ``step --all``."""
    return conn.execute("SELECT * FROM runs WHERE status = 'active' ORDER BY started_at").fetchall()


def turns_of(conn: sqlite3.Connection, run_id: int) -> list[sqlite3.Row]:
    return conn.execute(
        "SELECT * FROM turns WHERE run_id = ? ORDER BY ordinal", (run_id,)
    ).fetchall()


def last_turn(conn: sqlite3.Connection, run_id: int) -> sqlite3.Row | None:
    return conn.execute(
        "SELECT * FROM turns WHERE run_id = ? ORDER BY ordinal DESC LIMIT 1", (run_id,)
    ).fetchone()


def accepted_turn(conn: sqlite3.Connection, run_id: int, stage: str) -> sqlite3.Row | None:
    """The turn that counted for a stage — the answer to "did the gaincal work".

    At most one row, by the invariant enforced in :func:`set_turn_outcome`.
    """
    return conn.execute(
        "SELECT * FROM turns WHERE run_id = ? AND stage = ? AND outcome = 'accepted'",
        (run_id, stage),
    ).fetchone()


def job_of_turn(conn: sqlite3.Connection, turn_id: int) -> sqlite3.Row | None:
    return conn.execute(
        "SELECT * FROM jobs WHERE turn_id = ? ORDER BY id DESC LIMIT 1", (turn_id,)
    ).fetchone()


def unfinished_jobs(conn: sqlite3.Connection) -> list[sqlite3.Row]:
    """Jobs the driver must poll, and adopt rather than resubmit after a restart."""
    return conn.execute(
        "SELECT j.*, t.run_id, t.ordinal, t.stage FROM jobs j"
        " JOIN turns t ON t.id = j.turn_id"
        " WHERE j.state IN ('pending', 'running') ORDER BY j.id"
    ).fetchall()


def artifacts_of(conn: sqlite3.Connection, turn_id: int) -> list[sqlite3.Row]:
    return conn.execute(
        "SELECT * FROM artifacts WHERE turn_id = ? ORDER BY id", (turn_id,)
    ).fetchall()


# --------------------------------------------------------------------------
# The on-disk record, and rebuilding the index from it
# --------------------------------------------------------------------------
#
# write_turn_record and rebuild are two halves of one contract: whatever the
# first writes, the second must be able to turn back into rows. Test them
# against each other, never separately — a divergence here is what turns the
# index into the truth without anyone noticing.


def write_run_record(run_root: Path | str, record: dict) -> Path:
    """Write ``run.json``. Called once, when a run is initialised."""
    ensure_run_dirs(run_root, record["run_key"])
    p = run_json_path(run_root, record["run_key"])
    _atomic_write_json(p, record)
    return p


def write_turn_record(run_root: Path | str, run_key: str, record: dict) -> Path:
    """Write ``turns/NNNN.json`` for one completed turn.

    Written before the rows are inserted, so a crash between the two loses
    nothing that ``rebuild`` cannot recover.
    """
    p = turn_json_path(run_root, run_key, int(record["ordinal"]))
    p.parent.mkdir(parents=True, exist_ok=True)
    _atomic_write_json(p, record)
    return p


def _atomic_write_json(path: Path, obj: dict) -> None:
    """Write via a temporary file and rename, so a reader never sees a partial record."""
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(obj, indent=2, sort_keys=True))
    tmp.replace(path)


def read_run_records(run_root: Path | str) -> Iterator[dict]:
    """Yield every ``run.json`` under the run root, oldest first."""
    root = Path(run_root)
    if not root.is_dir():
        return
    for p in sorted(root.glob("*/run.json")):
        try:
            yield json.loads(p.read_text())
        except (OSError, json.JSONDecodeError) as exc:
            raise ValueError(f"unreadable run record {p}: {exc}") from exc


def read_turn_records(run_root: Path | str, run_key: str) -> Iterator[dict]:
    """Yield a run's turn records in ordinal order."""
    d = turns_dir(run_root, run_key)
    if not d.is_dir():
        return
    for p in sorted(d.glob("[0-9]*.json")):
        try:
            yield json.loads(p.read_text())
        except (OSError, json.JSONDecodeError) as exc:
            raise ValueError(f"unreadable turn record {p}: {exc}") from exc


def rebuild(conn: sqlite3.Connection, run_root: Path | str) -> dict[str, int]:
    """Reconstruct every table from the records under ``run_root``.

    Destructive to the index and only to the index: it empties the tables and
    replays the files. If this cannot reproduce what the driver wrote, the
    database has become the truth and the design is broken — which is why the
    round trip is the load-bearing test.

    Returns a count of rows written per table.
    """
    for table in ("metrics", "artifacts", "jobs", "turns", "runs"):
        conn.execute(f"DELETE FROM {table}")  # noqa: S608 - fixed table names
    conn.commit()

    counts = dict.fromkeys(("runs", "turns", "jobs", "artifacts", "metrics"), 0)

    for run_rec in read_run_records(run_root):
        run_id = insert_run(
            conn,
            run_key=run_rec["run_key"],
            ms_path=run_rec["ms_path"],
            workdir=run_rec["workdir"],
            backend=run_rec["backend"],
            executor=run_rec["executor"],
            telescope=run_rec.get("telescope"),
            started_at=run_rec.get("started_at"),
            status=run_rec.get("status", "active"),
        )
        if run_rec.get("finished_at") or run_rec.get("status") in ("done", "failed", "needs_human"):
            set_run_status(
                conn,
                run_id,
                run_rec.get("status", "done"),
                finished_at=run_rec.get("finished_at"),
            )
        counts["runs"] += 1

        for turn_rec in read_turn_records(run_root, run_rec["run_key"]):
            turn_id = insert_turn(
                conn,
                run_id=run_id,
                ordinal=int(turn_rec["ordinal"]),
                stage=turn_rec["stage"],
                attempt=int(turn_rec["attempt"]),
                brief=turn_rec.get("brief"),
                decision=turn_rec.get("decision"),
                tool=turn_rec.get("tool"),
                backend=turn_rec.get("backend"),
                model=turn_rec.get("model"),
                tokens_in=turn_rec.get("tokens_in"),
                tokens_out=turn_rec.get("tokens_out"),
                decide_wall_s=turn_rec.get("decide_wall_s"),
                outcome=turn_rec.get("outcome", "pending"),
                started_at=turn_rec.get("started_at"),
                note=turn_rec.get("note"),
            )
            # Replay the closing update too, so the "at most one accepted turn
            # per stage" invariant is re-derived rather than assumed.
            if turn_rec.get("outcome", "pending") != "pending":
                set_turn_outcome(
                    conn,
                    turn_id,
                    turn_rec["outcome"],
                    finished_at=turn_rec.get("finished_at"),
                    note=turn_rec.get("note"),
                )
            counts["turns"] += 1

            job = turn_rec.get("job")
            if job:
                job_id = insert_job(
                    conn,
                    turn_id=turn_id,
                    executor=job["executor"],
                    handle=job["handle"],
                    script_path=job.get("script_path"),
                    state=job.get("state", "pending"),
                    submitted_at=job.get("submitted_at"),
                    stdout_path=job.get("stdout_path"),
                    stderr_path=job.get("stderr_path"),
                )
                if job.get("state") in ("done", "failed"):
                    set_job_state(
                        conn,
                        job_id,
                        job["state"],
                        exit_code=job.get("exit_code"),
                        finished_at=job.get("finished_at"),
                    )
                counts["jobs"] += 1

            for art in turn_rec.get("artifacts", []):
                # Replay the recorded measurements. Re-measuring from disk here
                # would be wrong: a later attempt may have overwritten the file,
                # and the record is what says what this turn actually produced.
                insert_artifact(
                    conn,
                    turn_id=turn_id,
                    path=art["path"],
                    kind=art.get("kind", "other"),
                    size=art.get("size", 0),
                    checksum=art.get("checksum", ""),
                    mtime=art.get("mtime", ""),
                )
                counts["artifacts"] += 1

            for met in turn_rec.get("metrics", []):
                insert_metric(
                    conn,
                    run_id=run_id,
                    turn_id=turn_id,
                    name=met["name"],
                    value=met.get("value"),
                    unit=met.get("unit"),
                )
                counts["metrics"] += 1

    return counts

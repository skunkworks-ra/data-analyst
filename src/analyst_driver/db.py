def utc_now() -> str:
    """Current time as an ISO-8601 UTC string, second resolution.

    Timestamps are stored as TEXT so they are portable and sort lexically.
    """
    return datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def make_run_key(ms_path: Path | str, started_at: str | None = None) -> str:
    """Build a sortable, readable, unique key for a run.

    ``20260827T142530Z-3c286_b6-a91f`` — compact timestamp, MS name, and a short
    hash of the absolute MS path. The timestamp makes it sort chronologically;
    the hash disambiguates two runs started in the same second on different
    copies of a similarly-named MS.
    """
    started_at = started_at or utc_now()
    stamp = started_at.replace("-", "").replace(":", "")
    name = Path(ms_path).name
    for suffix in (".ms", ".MS"):
        if name.endswith(suffix):
            name = name[: -len(suffix)]
    slug = "".join(c if c.isalnum() else "_" for c in name).strip("_").lower()[:32] or "ms"
    digest = hashlib.sha256(str(Path(ms_path).absolute()).encode()).hexdigest()[:4]
    return f"{stamp}-{slug}-{digest}"


def checksum_path(path: Path | str, *, chunk: int = 1 << 20) -> str:
    """Content hash of a file, or of a directory tree such as a CASA caltable.

    CASA products are directories, so a plain file hash will not do. For a
    directory the hash covers each contained file's run-root-relative path and
    its bytes, walked in sorted order, so the result is stable across machines.

    Returns ``""`` if the path does not exist — an absent artifact is recorded
    as absent rather than raising, because a failed job legitimately produces
    nothing.
    """
    p = Path(path)
    if not p.exists():
        return ""
    h = hashlib.sha256()
    if p.is_file():
        _hash_file(h, p, chunk)
        return h.hexdigest()
    for f in sorted(x for x in p.rglob("*") if x.is_file()):
        h.update(str(f.relative_to(p)).encode())
        _hash_file(h, f, chunk)
    return h.hexdigest()


def _hash_file(h: Any, path: Path, chunk: int) -> None:
    with path.open("rb") as fh:
        while block := fh.read(chunk):
            h.update(block)


def path_size(path: Path | str) -> int:
    """Total bytes at a path, recursing into directories. 0 if absent."""
    p = Path(path)
    if not p.exists():
        return 0
    if p.is_file():
        return p.stat().st_size
    return sum(f.stat().st_size for f in p.rglob("*") if f.is_file())


def path_mtime(path: Path | str) -> str:
    """Modification time as an ISO-8601 UTC string. Empty string if absent."""
    p = Path(path)
    if not p.exists():
        return ""
    return datetime.fromtimestamp(p.stat().st_mtime, UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


# --------------------------------------------------------------------------
# Schema
# --------------------------------------------------------------------------

# PORTABILITY: `INTEGER PRIMARY KEY` is SQLite's rowid alias. On Postgres this
# becomes `INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`. That, and the
# `?` placeholder style below, are the only two things a port must change.
SCHEMA = """
CREATE TABLE IF NOT EXISTS runs (
    id          INTEGER PRIMARY KEY,
    run_key     TEXT    NOT NULL UNIQUE,
    started_at  TEXT    NOT NULL,
    finished_at TEXT,
    ms_path     TEXT    NOT NULL,
    workdir     TEXT    NOT NULL,
    telescope   TEXT,
    backend     TEXT    NOT NULL,
    executor    TEXT    NOT NULL,
    status      TEXT    NOT NULL
);

CREATE TABLE IF NOT EXISTS turns (
    id            INTEGER PRIMARY KEY,
    run_id        INTEGER NOT NULL REFERENCES runs(id),
    ordinal       INTEGER NOT NULL,
    stage         TEXT    NOT NULL,
    attempt       INTEGER NOT NULL,
    outcome       TEXT    NOT NULL,
    started_at    TEXT    NOT NULL,
    finished_at   TEXT,
    brief         TEXT,
    decision      TEXT,
    tool          TEXT,
    backend       TEXT,
    model         TEXT,
    tokens_in     INTEGER,
    tokens_out    INTEGER,
    decide_wall_s REAL,
    note          TEXT,
    UNIQUE (run_id, ordinal)
);

CREATE TABLE IF NOT EXISTS jobs (
    id           INTEGER PRIMARY KEY,
    turn_id      INTEGER NOT NULL REFERENCES turns(id),
    executor     TEXT    NOT NULL,
    handle       TEXT    NOT NULL,
    script_path  TEXT,
    state        TEXT    NOT NULL,
    submitted_at TEXT,
    finished_at  TEXT,
    exit_code    INTEGER,
    stdout_path  TEXT,
    stderr_path  TEXT
);

CREATE TABLE IF NOT EXISTS artifacts (
    id       INTEGER PRIMARY KEY,
    turn_id  INTEGER NOT NULL REFERENCES turns(id),
    path     TEXT    NOT NULL,
    kind     TEXT    NOT NULL,
    size     INTEGER,
    checksum TEXT,
    mtime    TEXT
);

CREATE TABLE IF NOT EXISTS metrics (
    id      INTEGER PRIMARY KEY,
    run_id  INTEGER NOT NULL REFERENCES runs(id),
    turn_id INTEGER REFERENCES turns(id),
    name    TEXT    NOT NULL,
    value   REAL,
    unit    TEXT
);

CREATE INDEX IF NOT EXISTS ix_turns_run    ON turns (run_id, ordinal);
CREATE INDEX IF NOT EXISTS ix_turns_stage  ON turns (run_id, stage, attempt);
CREATE INDEX IF NOT EXISTS ix_jobs_turn    ON jobs (turn_id);
CREATE INDEX IF NOT EXISTS ix_jobs_handle  ON jobs (handle);
CREATE INDEX IF NOT EXISTS ix_artifacts_turn ON artifacts (turn_id);
CREATE INDEX IF NOT EXISTS ix_metrics_name ON metrics (name);
"""


def connect(path: Path | str) -> sqlite3.Connection:
    """Open the index, creating the schema if absent.

    WAL plus a busy timeout so that two driver processes advancing different
    runs do not block each other. Write volume is a few rows per turn, so this
    is ample.
    """
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(p, timeout=30.0)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL")
    conn.execute("PRAGMA busy_timeout=30000")
    conn.execute("PRAGMA foreign_keys=ON")
    conn.executescript(SCHEMA)
    conn.commit()
    return conn



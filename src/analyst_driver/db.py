def insert_run(
    conn: sqlite3.Connection,
    *,
    run_key: str,
    ms_path: str,
    workdir: str,
    backend: str,
    executor: str,
    telescope: str | None = None,
    started_at: str | None = None,
    status: str = "active",
) -> int:
    cur = conn.execute(
        "INSERT INTO runs (run_key, started_at, ms_path, workdir, telescope,"
        " backend, executor, status) VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
        (run_key, started_at or utc_now(), ms_path, workdir, telescope, backend, executor, status),
    )
    conn.commit()
    return int(cur.lastrowid)


def set_run_status(
    conn: sqlite3.Connection, run_id: int, status: str, *, finished_at: str | None = None
) -> None:
    if status not in RUN_STATUS:
        raise ValueError(f"unknown run status {status!r}; expected one of {RUN_STATUS}")
    conn.execute(
        "UPDATE runs SET status = ?, finished_at = ? WHERE id = ?",
        (status, finished_at, run_id),
    )
    conn.commit()


def next_ordinal(conn: sqlite3.Connection, run_id: int) -> int:
    """Next turn number in a run. Monotonic; never reused, even after a failure."""
    row = conn.execute(
        "SELECT COALESCE(MAX(ordinal), 0) AS m FROM turns WHERE run_id = ?", (run_id,)
    ).fetchone()
    return int(row["m"]) + 1


def next_attempt(conn: sqlite3.Connection, run_id: int, stage: str) -> int:
    """Attempt number for the next turn at this stage. The first attempt is 1."""
    row = conn.execute(
        "SELECT COUNT(*) AS n FROM turns WHERE run_id = ? AND stage = ?", (run_id, stage)
    ).fetchone()
    return int(row["n"]) + 1


def insert_turn(
    conn: sqlite3.Connection,
    *,
    run_id: int,
    ordinal: int,
    stage: str,
    attempt: int,
    brief: str | None = None,
    decision: dict | str | None = None,
    tool: str | None = None,
    backend: str | None = None,
    model: str | None = None,
    tokens_in: int | None = None,
    tokens_out: int | None = None,
    decide_wall_s: float | None = None,
    outcome: str = "pending",
    started_at: str | None = None,
    note: str | None = None,
) -> int:
    if outcome not in TURN_OUTCOME:
        raise ValueError(f"unknown turn outcome {outcome!r}; expected one of {TURN_OUTCOME}")
    if isinstance(decision, dict):
        decision = json.dumps(decision, sort_keys=True)
    cur = conn.execute(
        "INSERT INTO turns (run_id, ordinal, stage, attempt, outcome, started_at,"
        " brief, decision, tool, backend, model, tokens_in, tokens_out,"
        " decide_wall_s, note)"
        " VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
        (
            run_id,
            ordinal,
            stage,
            attempt,
            outcome,
            started_at or utc_now(),
            brief,
            decision,
            tool,
            backend,
            model,
            tokens_in,
            tokens_out,
            decide_wall_s,
            note,
        ),
    )
    conn.commit()
    return int(cur.lastrowid)


def set_turn_outcome(
    conn: sqlite3.Connection,
    turn_id: int,
    outcome: str,
    *,
    finished_at: str | None = None,
    note: str | None = None,
) -> None:
    """Close a turn.

    Marking a turn ``accepted`` demotes any previously accepted turn for the
    same (run, stage) to ``retried``, so the invariant "at most one accepted
    turn per stage" holds without the caller having to remember it.
    """
    if outcome not in TURN_OUTCOME:
        raise ValueError(f"unknown turn outcome {outcome!r}; expected one of {TURN_OUTCOME}")
    if outcome == "accepted":
        row = conn.execute("SELECT run_id, stage FROM turns WHERE id = ?", (turn_id,)).fetchone()
        if row is None:
            raise KeyError(f"no turn with id {turn_id}")
        conn.execute(
            "UPDATE turns SET outcome = 'retried'"
            " WHERE run_id = ? AND stage = ? AND outcome = 'accepted' AND id <> ?",
            (row["run_id"], row["stage"], turn_id),
        )
    conn.execute(
        "UPDATE turns SET outcome = ?, finished_at = ?, note = COALESCE(?, note) WHERE id = ?",
        (outcome, finished_at or utc_now(), note, turn_id),
    )
    conn.commit()


def insert_job(
    conn: sqlite3.Connection,
    *,
    turn_id: int,
    executor: str,
    handle: str,
    script_path: str | None = None,
    state: str = "pending",
    submitted_at: str | None = None,
    stdout_path: str | None = None,
    stderr_path: str | None = None,
) -> int:
    if state not in JOB_STATE:
        raise ValueError(f"unknown job state {state!r}; expected one of {JOB_STATE}")
    cur = conn.execute(
        "INSERT INTO jobs (turn_id, executor, handle, script_path, state,"
        " submitted_at, stdout_path, stderr_path) VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
        (
            turn_id,
            executor,
            handle,
            script_path,
            state,
            submitted_at or utc_now(),
            stdout_path,
            stderr_path,
        ),
    )
    conn.commit()
    return int(cur.lastrowid)


def set_job_state(
    conn: sqlite3.Connection,
    job_id: int,
    state: str,
    *,
    exit_code: int | None = None,
    finished_at: str | None = None,
) -> None:
    if state not in JOB_STATE:
        raise ValueError(f"unknown job state {state!r}; expected one of {JOB_STATE}")
    terminal = state in ("done", "failed")
    conn.execute(
        "UPDATE jobs SET state = ?, exit_code = COALESCE(?, exit_code),"
        " finished_at = COALESCE(?, finished_at) WHERE id = ?",
        (state, exit_code, (finished_at or utc_now()) if terminal else None, job_id),
    )
    conn.commit()


def insert_artifact(
    conn: sqlite3.Connection,
    *,
    turn_id: int,
    path: str,
    kind: str,
    size: int | None = None,
    checksum: str | None = None,
    mtime: str | None = None,
) -> int:
    """Record one artifact, measuring it from disk if not told otherwise.

    The checksum is what lets the index survive the retry-overwrite defect in
    the ``ms_modify`` tools: a second attempt at a stage overwrites the first
    attempt's caltable, so the file itself cannot say which turn produced it.
    """
    if size is None:
        size = path_size(path)
    if checksum is None:
        checksum = checksum_path(path)
    if mtime is None:
        mtime = path_mtime(path)
    cur = conn.execute(
        "INSERT INTO artifacts (turn_id, path, kind, size, checksum, mtime)"
        " VALUES (?, ?, ?, ?, ?, ?)",
        (turn_id, path, kind, size, checksum, mtime),
    )
    conn.commit()
    return int(cur.lastrowid)


def insert_metric(
    conn: sqlite3.Connection,
    *,
    run_id: int,
    name: str,
    value: float | None,
    unit: str | None = None,
    turn_id: int | None = None,
) -> int:
    cur = conn.execute(
        "INSERT INTO metrics (run_id, turn_id, name, value, unit) VALUES (?, ?, ?, ?, ?)",
        (run_id, turn_id, name, value, unit),
    )
    conn.commit()
    return int(cur.lastrowid)


